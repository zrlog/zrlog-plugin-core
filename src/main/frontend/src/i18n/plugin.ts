export const normalizeLang = (lang?: string): PluginLang => /^en(?:[-_]|$)/i.test(lang?.trim() || "") ? "en_US" : "zh_CN";

const resources: Record<PluginLang, PluginI18nResource> = {zh_CN: zhCN, en_US: enUS};
let currentLang: PluginLang = "zh_CN";

export const setLanguage = (lang?: string) => { currentLang = normalizeLang(lang); };
export const getLanguage = (): PluginLang => currentLang;
export const getRes = (): PluginI18nResource => resources[currentLang];
export const getPluginI18n = (lang?: string): PluginI18nResource => resources[normalizeLang(lang)];
export const formatText = (template: string, values: Record<string, string | number>): string =>
    template.replace(/\{(\w+)\}/g, (placeholder, key: string) => values[key] === undefined ? placeholder : String(values[key]));
